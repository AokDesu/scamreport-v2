import { localEnvironment } from './local-env';
async function run(command:string[]) {
  const child=Bun.spawn(command,{stdout:'inherit',stderr:'inherit'});
  if(await child.exited!==0) throw new Error(command.join(' ')+' failed');
}
await run(['supabase','start','--exclude','studio,postgres-meta,realtime,imgproxy,edge-runtime,logflare,vector,supavisor']);
const values=localEnvironment();
const lines={SUPABASE_URL:values.SUPABASE_URL,SUPABASE_ANON_KEY:values.SUPABASE_ANON_KEY,VITE_SUPABASE_URL:values.SUPABASE_URL,VITE_SUPABASE_ANON_KEY:values.SUPABASE_ANON_KEY,WEB_ORIGIN:'http://localhost:8080'};
const file=Bun.file('.env');
if (await file.exists()) {
  const prior=await file.text();
  if (!prior.startsWith('# Generated by bun run local:up')) throw new Error('Refusing to overwrite a hand-written .env. Move it aside before local:up.');
}
await Bun.write('.env','# Generated by bun run local:up; local public key only; never commit.\n'+Object.entries(lines).map(([key,value])=>key+'='+value).join('\n')+'\n');
await run(['docker','compose','up','--build','-d','--wait']);
console.info('Web: http://localhost:8080 | API/OpenAPI: http://localhost:3000/openapi');
